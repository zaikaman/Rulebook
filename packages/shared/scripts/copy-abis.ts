#!/usr/bin/env node
/**
 * Copies the ABIs of every deployed contract from `contracts/out` into a typed
 * `src/abi/index.ts`. The committed output is checked against a fresh build in CI, so a
 * contract change that is not re-generated fails the build instead of drifting silently.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = join(HERE, '..');
const REPO_ROOT = join(PACKAGE_ROOT, '..', '..');
const OUT_DIR = join(REPO_ROOT, 'contracts', 'out');
const TARGET = join(PACKAGE_ROOT, 'src', 'abi', 'index.ts');

const CONTRACTS = [
  { name: 'WorkflowAgentV2', exportName: 'workflowAgentV2Abi' },
  { name: 'WorkflowAgentFactoryV2', exportName: 'workflowAgentFactoryV2Abi' },
  { name: 'WorkflowVaultV2', exportName: 'workflowVaultV2Abi' },
  { name: 'WorkflowVaultFactoryV2', exportName: 'workflowVaultFactoryV2Abi' },
  { name: 'WorkflowProgramValidatorV2', exportName: 'workflowProgramValidatorV2Abi' },
] as const;

if (!existsSync(OUT_DIR)) {
  throw new Error('contracts/out is missing: run `forge build` before generating ABIs');
}

const sections = CONTRACTS.map(({ name, exportName }) => {
  const artifactPath = join(OUT_DIR, `${name}.sol`, `${name}.json`);
  if (!existsSync(artifactPath)) {
    throw new Error(`Missing artifact ${artifactPath}: run \`forge build\``);
  }
  const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as { abi: unknown[] };
  return `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;`;
});

const header = `// AUTO-GENERATED by packages/shared/scripts/copy-abis.ts from contracts/out.
// Do not edit by hand: run \`npm run generate -w packages/shared\`.

`;

const footer = `
export const abis = {
${CONTRACTS.map(({ exportName }) => `  ${exportName},`).join('\n')}
} as const;
`;

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, `${header}${sections.join('\n\n')}\n${footer}`);
console.log(`generated ${TARGET}`);
